import { chromium } from 'playwright';
const SP = process.env.SP, URL = 'http://localhost:8090/';
const fails = []; const ok = (n, c, x = '') => { console.log((c ? 'PASS ' : 'FAIL ') + n + (x ? '  ' + x : '')); if (!c) fails.push(n); };
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, colorScheme: 'dark' });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
p.on('dialog', d => d.accept());
const shot = n => p.screenshot({ path: `${SP}/cshots/${n}.png` });
await p.goto(URL); await p.waitForTimeout(1500);
await shot('01-welcome');
ok('permission screen', await p.getByText('Allow access to photos').isVisible());
await p.getByText('Allow access to photos').click();
await p.waitForTimeout(800);
await shot('02-scanning');
await p.waitForFunction(() => !document.body.innerText.includes('Checking your photos'), null, { timeout: 30000 });
await p.waitForTimeout(1200);
await shot('03-dashboard');
const dash = await p.locator('body').innerText();
ok('similar sets found', /Similar shots[\s\S]*?\d+ sets/.test(dash), dash.match(/Similar shots[^\n]*\n[^\n]*/)?.[0]);
ok('accidental found', /Accidental shots[\s\S]{0,80}\n6\n/.test(dash));
await p.getByText('Similar shots', { exact: true }).click(); await p.waitForTimeout(800);
await shot('04-similar');
const setsText = await p.locator('body').innerText();
ok('7 sets plus WhatsApp duplicate', (setsText.match(/Save /g) || []).length >= 7, String((setsText.match(/Save /g) || []).length));
await p.getByText(/★ Keep/).first().click(); await p.waitForTimeout(800);
await shot('05-group');
const g = await p.locator('body').innerText();
ok('group shows reasons', /Eyes closed|Blurry|Grainy|Similar shot|Less sharp/.test(g));
const delBtn = p.getByText(/^Delete \d+ ·/);
const label = await delBtn.innerText();
await delBtn.click(); await p.waitForTimeout(1000);
await shot('06-after-delete');
ok('moved to next set after delete', /Set \d+ of \d+/.test(await p.locator('body').innerText()), label);
await p.goBack(); await p.waitForTimeout(500); await p.goBack(); await p.waitForTimeout(800);
await p.getByText('Accidental shots').click(); await p.waitForTimeout(800);
await shot('07-accidental');
ok('accidental preselected', /Delete 6 ·/.test(await p.locator('body').innerText()));
await p.goBack(); await p.waitForTimeout(500);
// Albums + search
await p.getByText('Albums', { exact: true }).last().click(); await p.waitForTimeout(800);
await shot('08-albums');
const al = await p.locator('body').innerText();
ok('albums listed', /Documents & receipts/.test(al) && /Screenshots/.test(al) && /Pets/.test(al) && /People/.test(al));
await p.getByPlaceholder(/Search/).fill('woolworths'); await p.keyboard.press('Enter'); await p.waitForTimeout(800);
await shot('09-search');
ok('search finds receipts', /2 items/.test(await p.locator('body').innerText()));
// Photo view + editor
await p.locator('img').nth(1).click({ force: true }).catch(() => {});
await p.waitForTimeout(500);
await p.goBack(); await p.waitForTimeout(400); await p.goBack(); await p.waitForTimeout(400);
await p.getByText('Clean', { exact: true }).last().click(); await p.waitForTimeout(500);
await p.getByText('Blurry', { exact: true }).click(); await p.waitForTimeout(700);
await p.locator('[aria-label^="Photo"]').first().click(); await p.waitForTimeout(800);
await shot('10-photo');
ok('photo details', /Quality/.test(await p.locator('body').innerText()));
await p.getByText('Edit', { exact: true }).last().click(); await p.waitForTimeout(800);
await p.getByText('Auto').click(); await p.waitForTimeout(500);
await shot('11-edit-adjust');
await p.getByText('Crop & rotate').click(); await p.getByText('Square').click(); await p.waitForTimeout(400);
await shot('12-edit-crop');
await p.getByText('Save as copy').click(); await p.waitForTimeout(1200);
ok('edit saved and closed', !(await p.getByText('Save as copy').isVisible().catch(() => false)));
await p.goBack(); await p.waitForTimeout(400); await p.goBack(); await p.waitForTimeout(400);
// Compress
await p.getByText('Shrink large photos').click(); await p.waitForTimeout(800);
await shot('13-compress');
await p.getByText(/^Shrink \d+ photos/).click();
await p.waitForSelector('text=Smaller copies saved', { timeout: 60000 });
await shot('14-compress-done');
await p.getByText('Move originals to Bin').click(); await p.waitForTimeout(1000);
ok('originals binned', /Originals moved to the Bin/.test(await p.locator('body').innerText()));
await p.goBack(); await p.waitForTimeout(500);
// Bin
await p.getByText('Bin', { exact: true }).last().click(); await p.waitForTimeout(1000);
await shot('15-bin');
const binText = await p.locator('body').innerText();
ok('bin lists deleted items', /\d+ items ·/.test(binText), binText.match(/\d+ items · [^\n]*/)?.[0]);
await p.getByText('Settings', { exact: true }).last().click(); await p.waitForTimeout(600);
await shot('16-settings');
await p.setViewportSize({ width: 320, height: 640 });
await p.getByText('Clean', { exact: true }).last().click(); await p.waitForTimeout(600);
await shot('17-dashboard-320');
const overflow = await p.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
ok('no horizontal overflow at 320px', !overflow);
ok('no JS errors', errs.length === 0, errs.slice(0, 5).join(' | '));
await b.close();
console.log(fails.length ? `${fails.length} FAILED` : 'ALL PASSED');
